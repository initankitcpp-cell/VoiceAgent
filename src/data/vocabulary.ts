export const levels: Level[] = ['Beginner', 'Intermediate', 'Advanced'];
export const vocabulary: Word[] = levels.flatMap((level) =>
  entries[level].map(([word, part, meaning, example, hint], index) => {
    const answer = index % 3;
    const distractors = [entries[level][(index + 7) % 20][2], entries[level][(index + 13) % 20][2]];
    distractors.splice(answer, 0, meaning);
    return {
      id: word.toLowerCase(),
      word,
      level,
      part,
      meaning,
      example,
      hint,
      quiz: { question: `What does “${word.toLowerCase()}” mean?`, options: distractors, answer },
    };
  }),
);
