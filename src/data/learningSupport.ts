export function grammarLearningNote(issue: GrammarIssue, languageId: string): string | null {
  if (!(languageId in learningSupport)) return null;
  const copy = learningSupport[languageId as BundledLanguageId];
  const context = `${issue.ruleId} ${issue.category} ${issue.message}`;
  if (/I_AM|VERB_AGR|AGREEMENT|third.person|subject.verb/i.test(context)) return copy.agreement;
  if (/ARTICLE|A_AN|DETERMINER/i.test(context)) return copy.article;
  if (/MORFOLOGIK|SPELL|TYPOS/i.test(context)) return copy.spelling;
  if (/UPPERCASE|LOWERCASE|capital/i.test(context)) return copy.capitalization;
  if (/PUNCT|COMMA|PERIOD/i.test(context)) return copy.punctuation;
  if (/TENSE|PAST|PRESENT/i.test(context)) return copy.tense;
  return copy.general;
}
